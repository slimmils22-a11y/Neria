class CertificateManager
{
    // ── Config keys ───────────────────────────────────────────────
    const CFG_ENABLED       = 'NERIA_CERT_ENABLED';
    const CFG_SERIAL_PREFIX = 'NERIA_CERT_SERIAL_PREFIX';
    const CFG_TITLE         = 'NERIA_CERT_TITLE';
    const CFG_SUBTITLE      = 'NERIA_CERT_SUBTITLE';
    const CFG_BODY          = 'NERIA_CERT_BODY';
    const CFG_QR_ENABLED    = 'NERIA_CERT_QR_ENABLED';
    const CFG_QR_URL        = 'NERIA_CERT_QR_URL';

    const TABLE = 'neria_certificate';

    /** @var \Neria */
    private $module;
    /** @var \Db */
    private $db;
    /** @var int */
    private $idShop;

    public function __construct(\Neria $module)
    {
        $this->module = $module;
        $this->db     = \Db::getInstance();
        $this->idShop = (int) \Context::getContext()->shop->id;
    }

    // ============================================================
    // ÉMISSION D'UN CERTIFICAT
    // ============================================================

    /**
     * Génère le PDF et l'envoie par email au client.
     * Retourne '' si succès, message d'erreur sinon.
     *
     * @param int    $idOrder
     * @param int    $idProduct
     * @param int    $idOrderDetail
     * @param string $serialNumber  Vide = auto-généré
     * @param string $artisanNote   Note libre de l'artisan
     * @param bool   $sendEmail     Envoyer ou juste générer
     */
    public function issue(
        int    $idOrder,
        int    $idProduct,
        int    $idOrderDetail,
        string $serialNumber = '',
        string $artisanNote  = '',
        bool   $sendEmail    = true
    ): string {
        // ── Commande & client ─────────────────────────────────────
        $order = new \Order($idOrder);
        if (!\Validate::isLoadedObject($order)) {
            return AdminTranslator::t('msg.certificate_order_not_found');
        }

        $customer = new \Customer((int) $order->id_customer);
        $customerName = trim($customer->firstname . ' ' . $customer->lastname);
        $customerEmail = $customer->email;

        // ── Langue du client (même algorithme que EmailRenderer pour l'email,
        //    afin que le PDF joint corresponde à la langue de l'email) ──────
        // Résolue AVANT de charger le produit ci-dessous : le nom produit
        // doit être chargé dans CETTE langue, pas celle du contexte BO de
        // l'employé qui déclenche l'émission — sinon un marchand dont le BO
        // est en arabe/chinois mais qui certifie une commande d'un client
        // français voyait "PRODUIT" s'afficher en rectangles vides (police
        // WinAnsi choisie pour $lang='fr' ne sait pas rendre l'arabe/CJK).
        $lang = $this->resolveCertificateLang($order, (int) $customer->id_lang);

        // ── Produit ───────────────────────────────────────────────
        $idLangProduct = (int) (\Language::getIdByIso($lang) ?: \Context::getContext()->language->id);
        $product = new \Product($idProduct, false, $idLangProduct);
        $productName = $product->name ?: 'Produit #' . $idProduct;

        // ── Numéro de série ───────────────────────────────────────
        // Sous accès concurrent (émissions quasi simultanées), MAX(id_certificate)+1
        // peut donner deux fois le même numéro avant que l'un des deux INSERT
        // n'ait posé la contrainte UNIQUE. Si le numéro est auto-généré (pas
        // fourni explicitement par l'appelant), on retente avec un offset
        // croissant plutôt que d'échouer un certificat pourtant légitime.
        $autoGenerated = ($serialNumber === '');
        if ($autoGenerated) {
            $serialNumber = $this->generateSerial();
        }

        if ($this->serialExists($serialNumber)) {
            if (!$autoGenerated) {
                return AdminTranslator::tVars('msg.certificate_serial_exists', ['serial' => $serialNumber]);
            }
            $resolved = false;
            for ($offset = 1; $offset <= 5; $offset++) {
                $candidate = $this->generateSerial($offset);
                if (!$this->serialExists($candidate)) {
                    $serialNumber = $candidate;
                    $resolved     = true;
                    break;
                }
            }
            if (!$resolved) {
                return AdminTranslator::tVars('msg.certificate_serial_exists', ['serial' => $serialNumber]);
            }
        }

        // ── Génère le PDF ─────────────────────────────────────────
        $pdfResult = $this->generatePdf(
            $serialNumber, $order, $customerName, $productName, $artisanNote, $lang
        );
        if (isset($pdfResult['error'])) {
            return $pdfResult['error'];
        }

        $pdfContent = $pdfResult['content'];
        $pdfPath    = $pdfResult['path'];

        // ── Sauvegarde en DB ──────────────────────────────────────
        $inserted = $this->db->insert(self::TABLE, [
            // id_shop de LA COMMANDE, pas $this->idShop (contexte BO de
            // l'employé qui déclenche l'émission) : un employé en contexte
            // "toutes les boutiques" (ou dont le contexte BO courant diffère
            // de la boutique de la commande) émettant un certificat pour une
            // commande d'une AUTRE boutique enregistrait sinon le certificat
            // sous la mauvaise boutique — invisible dans getByOrder()/
            // getAll() de la vraie boutique, polluant les stats de l'autre.
            'id_shop'         => (int) $order->id_shop,
            // Stocké directement (pas seulement dérivable via id_order) :
            // permet à GdprAuditManager::purgeCustomerData() de purger ce
            // certificat même si la commande liée a depuis été supprimée du
            // BO PrestaShop — sans cette colonne, un certificat (nom client
            // en clair) survivait indéfiniment à une demande d'effacement
            // RGPD dès que la commande n'existait plus pour le JOIN.
            'id_customer'     => (int) $order->id_customer,
            'id_order'        => $idOrder,
            'id_product'      => $idProduct,
            'id_order_detail' => $idOrderDetail,
            'serial_number'   => pSQL($serialNumber),
            'customer_name'   => pSQL($customerName),
            'product_name'    => pSQL($productName),
            'artisan_note'    => pSQL($artisanNote),
            'pdf_path'        => pSQL($pdfPath),
            'emailed'         => 0,
            'date_issued'     => date('Y-m-d H:i:s'),
            'date_add'        => date('Y-m-d H:i:s'),
        ]);

        if (!$inserted) {
            // Doublon de clé unique sur serial_number (émissions quasi simultanées)
            // ou autre échec DB — on ne continue jamais avec un id_certificate invalide.
            if (class_exists('WatchdogManager')) {
                (new WatchdogManager($this->module))->warning(
                    'Échec d\'émission de certificat : ' . $serialNumber . ' — ' . $productName
                    . ' (commande #' . $idOrder . ', client : ' . $customerEmail . ')',
                    '', 'CertificateManager'
                );
            }
            return AdminTranslator::t('msg.certificate_save_failed');
        }

        $idCertificate = (int) $this->db->Insert_ID();

        // ── Envoi email ───────────────────────────────────────────
        if ($sendEmail) {
            $err = $this->sendCertificateEmail(
                $customerEmail, $customerName, $productName,
                $serialNumber, $pdfContent, $order, (int) $customer->id_lang
            );
            if ($err !== '') {
                return $err;
            }

            $this->db->update(self::TABLE, ['emailed' => 1],
                '`id_certificate` = ' . $idCertificate);
        }

        // ── Log Watchdog ──────────────────────────────────────────
        if (class_exists('WatchdogManager')) {
            (new WatchdogManager($this->module))->info(
                'Certificat émis : ' . $serialNumber . ' — ' . $productName
                . ' (commande #' . $idOrder . ', client : ' . $customerEmail . ')',
                '', 'CertificateManager'
            );
        }

        return '';
    }

    /**
     * Retélécharge le PDF d'un certificat déjà émis.
     * Retourne le contenu binaire du PDF ou '' si erreur.
     */
    public function redownload(int $idCertificate): array
    {
        // Pas de filtre `id_shop` = $this->idShop (contexte BO courant de
        // l'employé) : ce bouton est posté depuis la fiche commande PS
        // (order_certificate_block.tpl → action sur AdminModules&configure=
        // neria), dont le contexte de boutique en tête de BO peut très bien
        // différer de celle de LA COMMANDE affichée (cas normal en
        // multi-boutique tant que l'employé n'a pas explicitement changé de
        // sélecteur). id_certificate est déjà une clé globalement unique
        // (comme id_order pour getByOrder() ci-dessous) — y ajouter ce
        // filtre ne fait que réintroduire, pour le téléchargement, l'exacte
        // "invisibilité inter-boutique" qu'issue() documente déjà avoir
        // corrigée pour l'écriture (id_shop DE LA COMMANDE, pas $this->idShop).
        $row = $this->db->getRow(
            'SELECT * FROM `' . _DB_PREFIX_ . self::TABLE . '`
             WHERE `id_certificate` = ' . $idCertificate
        );
        if (!$row) {
            return ['error' => AdminTranslator::t('msg.certificate_not_found')];
        }

        $order    = new \Order((int) $row['id_order']);
        $customer = new \Customer((int) $order->id_customer);
        $lang     = $this->resolveCertificateLang($order, (int) $customer->id_lang);
        $result   = $this->generatePdf(
            $row['serial_number'],
            $order,
            $row['customer_name'],
            $row['product_name'],
            $row['artisan_note'] ?? '',
            $lang
        );
        return $result;
    }

    // ============================================================
    // GÉNÉRATION PDF
    // ============================================================

    /**
     * Résout la langue à utiliser pour le PDF ET l'email du certificat, avec
     * le même algorithme que EmailRenderer (TranslationEngine::resolveOptimalLang) :
     * compte client si boutique multi-langues, sinon pays de facturation.
     * Garantit que le PDF joint est dans la même langue que l'email qui
     * l'accompagne (EmailRenderer applique indépendamment le même algorithme
     * sur les mêmes données de commande/client).
     */
    private function resolveCertificateLang(\Order $order, int $idLang): string
    {
        $engine = new \TranslationEngine($this->module);

        // Round 158 : quand NERIA_AUTO_LANG est désactivé, EmailRenderer::
        // resolveEmailLang() court-circuite entièrement l'algorithme pays/
        // code-postal et retombe sur la langue brute du compte client
        // (langFromId($idLang)) — cette méthode ne le faisait jamais et
        // appliquait TOUJOURS l'algorithme pays, cassant la parité PDF/email
        // que le commentaire de classe ci-dessus annonce pourtant garantir :
        // un client dont le compte est en langue A mais dont l'adresse de
        // facturation est dans un pays de langue B recevait un PDF en B et
        // un email en A dès que le marchand désactivait la détection auto.
        if (class_exists('ConfigManager') && !(new \ConfigManager($this->module))->isAutoLangEnabled()) {
            return $engine->langFromId($idLang);
        }

        $countryIso = '';
        $postcode   = '';
        if ($order->id_address_invoice) {
            $address = new \Address((int) $order->id_address_invoice);
            if (\Validate::isLoadedObject($address)) {
                $countryIso = (string) (\Country::getIsoById((int) $address->id_country) ?: '');
                $postcode   = (string) $address->postcode;
            }
        }

        return $engine->resolveOptimalLang($idLang, $countryIso, $postcode);
    }

    /**
     * Choisit les polices TCPDF adaptées au script de la langue. Les
     * polices core (helvetica/times) sont limitées à l'encodage WinAnsi :
     * arabe, CJK et cyrillique s'y affichent en rectangles vides. Les
     * polices ci-dessous sont fournies avec TCPDF (fonts/*.php), aucun
     * fichier ni dépendance à ajouter au module.
     *
     * @return array{0: string, 1: string, 2: bool} [$fontSans, $fontSerif, $isRtl]
     */
    private function pdfFontsForLang(string $lang): array
    {
        switch ($lang) {
            case 'ar':
                // Police arabe (script RTL) — un seul style disponible,
                // voir pdfSetFont() qui ignore B/I pour cette police.
                return ['aealarabiya', 'aealarabiya', true];
            case 'zh':
                return ['cid0cs', 'cid0cs', false]; // chinois simplifié
            case 'tw':
                return ['cid0ct', 'cid0ct', false]; // chinois traditionnel
            case 'ja':
                return ['cid0jp', 'cid0jp', false];
            case 'ko':
                return ['cid0kr', 'cid0kr', false];
            case 'ru':
                // Cyrillique : dejavusans (styles complets) + freeserif
                return ['dejavusans', 'freeserif', false];
            default:
                return ['helvetica', 'times', false];
        }
    }

    /**
     * Applique une police/taille en tenant compte des polices non-Latin
     * (aealarabiya, cid0*) qui ne fournissent qu'un seul style TCPDF —
     * demander 'B' ou 'I' sur ces polices lève une erreur TCPDF.
     */
    private function pdfSetFont(\TCPDF $pdf, string $family, string $style, int $size): void
    {
        $singleStyleFamilies = ['aealarabiya', 'cid0cs', 'cid0ct', 'cid0jp', 'cid0kr'];
        if (in_array($family, $singleStyleFamilies, true)) {
            $style = '';
        }
        $pdf->SetFont($family, $style, $size);
    }

    private function generatePdf(
        string $serial,
        \Order $order,
        string $customerName,
        string $productName,
        string $artisanNote,
        string $lang
    ): array {
        $tcpdfPath = _PS_ROOT_DIR_ . '/vendor/tecnickcom/tcpdf/tcpdf.php';
        if (!file_exists($tcpdfPath)) {
            return ['error' => AdminTranslator::t('msg.certificate_tcpdf_missing')];
        }
        require_once $tcpdfPath;

        // Configuration::get(..., (int) $order->id_shop) : round 106, le nom
        // de boutique imprimé sur le PDF ignorait la boutique réelle de LA
        // COMMANDE — même piège déjà corrigé pour {shop_url} plus bas dans
        // cette même méthode (bascule temporaire de Context::shop), mais qui
        // ne couvrait pas ce $shopName-ci, résolu AVANT la bascule.
        $shopName   = (string) \Configuration::get('PS_SHOP_NAME', null, null, (int) $order->id_shop);
        $shopDomain = \Tools::getShopDomainSsl(true);
        $dateStr    = \NeriaTools::formatDate($order->date_add, $lang);
        $issuedStr  = \NeriaTools::formatDate('now', $lang);

        // Instancié ici (et non plus seulement plus bas pour les libellés du
        // tableau) car les valeurs PAR DÉFAUT du titre/sous-titre/corps
        // doivent elles aussi être traduites — auparavant codées en dur en
        // français, elles s'affichaient dans cette langue quelle que soit
        // celle du client tant que le marchand n'avait pas personnalisé ces
        // 3 champs en configuration.
        $engine = new \TranslationEngine($this->module);

        $title    = (string) \Configuration::get(self::CFG_TITLE)    ?: $engine->get('certificate_email', 'certificate_pdf_default_title', $lang);
        $subtitle = (string) \Configuration::get(self::CFG_SUBTITLE) ?: $engine->get('certificate_email', 'certificate_pdf_default_subtitle', $lang);
        $bodyText = (string) \Configuration::get(self::CFG_BODY)     ?: $engine->get('certificate_email', 'certificate_pdf_default_body', $lang);

        // Substitution de {shop_name} même lorsque le marchand a personnalisé
        // ces champs — auparavant seule la valeur par défaut (fallback) était
        // interpolée, une valeur configurée manuellement affichait la variable
        // brute non résolue.
        $pdfVars  = ['{shop_name}' => $shopName];
        $title    = strtr($title, $pdfVars);
        $subtitle = strtr($subtitle, $pdfVars);
        $bodyText = strtr($bodyText, $pdfVars);

        $qrEnabled = (bool) \Configuration::get(self::CFG_QR_ENABLED);
        $qrBaseUrl = (string) \Configuration::get(self::CFG_QR_URL) ?: $shopDomain;
        // getShopDomainSsl(true) peut malgré tout retourner du http:// si le
        // SSL n'est pas activé côté PS (PS_SSL_ENABLED) — un QR code sur un
        // certificat imprimé/PDF ne doit jamais pointer vers une URL non
        // chiffrée. cert_qr_url (BO) est déjà validé en https:// à
        // l'enregistrement ; ce garde-fou ne couvre donc que le fallback.
        if (stripos($qrBaseUrl, 'http://') === 0) {
            $qrBaseUrl = 'https://' . substr($qrBaseUrl, 7);
        }

        // Signature manuscrite
        $sigPath  = '';
        $sigRow   = $this->db->getRow(
            'SELECT `image_path` FROM `' . _DB_PREFIX_ . 'neria_signature`
             WHERE `is_active` = 1 AND `id_shop` = ' . $this->idShop . '
             ORDER BY `date_upd` DESC'
        );
        if ($sigRow && !empty($sigRow['image_path'])) {
            $candidate = _PS_MODULE_DIR_ . 'neria/' . ltrim($sigRow['image_path'], '/');
            if (file_exists($candidate)) {
                $sigPath = $candidate;
            }
        }

        // Logo boutique
        $logoPath = '';
        $psLogo   = _PS_IMG_DIR_ . \Configuration::get('PS_LOGO');
        if (file_exists($psLogo)) {
            $logoPath = $psLogo;
        }

        // ── Police adaptée au script de la langue ──────────────────
        // Les polices core TCPDF (helvetica/times) sont limitées à
        // l'encodage WinAnsi : arabe, CJK et cyrillique s'affichent en
        // rectangles vides avec elles. Les polices ci-dessous sont fournies
        // avec TCPDF (aucune dépendance externe) et couvrent ces scripts.
        [$fontSans, $fontSerif, $isRtl] = $this->pdfFontsForLang($lang);

        // ── PDF ───────────────────────────────────────────────────
        try {
            $pdf = new \TCPDF('P', 'mm', 'A4', true, 'UTF-8', false);
            $pdf->SetCreator('Neria');
            $pdf->SetAuthor($shopName);
            $pdf->SetTitle($title . ' — ' . $serial);
            $pdf->SetMargins(20, 20, 20);
            $pdf->SetAutoPageBreak(true, 20);
            $pdf->setPrintHeader(false);
            $pdf->setPrintFooter(false);
            $pdf->setRTL($isRtl);
            $pdf->AddPage();

            // ── Fond luxe (rectangle or pâle) ────────────────────
            $pdf->SetFillColor(250, 246, 240);
            $pdf->Rect(10, 10, 190, 277, 'F');

            // ── Bordure dorée ─────────────────────────────────────
            $pdf->SetDrawColor(179, 139, 89);
            $pdf->SetLineWidth(0.8);
            $pdf->Rect(12, 12, 186, 273);
            $pdf->SetLineWidth(0.3);
            $pdf->Rect(14, 14, 182, 269);

            $y = 22;

            // ── Logo ──────────────────────────────────────────────
            if ($logoPath !== '') {
                $pdf->Image($logoPath, 85, $y, 40, 0, '', '', '', false, 300);
                $y += 28;
            } else {
                $this->pdfSetFont($pdf, $fontSans, 'B', 16);
                $pdf->SetTextColor(26, 26, 46);
                $pdf->SetXY(20, $y);
                $pdf->Cell(170, 10, $shopName, 0, 1, 'C');
                $y += 14;
            }

            // ── Filet or ─────────────────────────────────────────
            $pdf->SetDrawColor(179, 139, 89);
            $pdf->SetLineWidth(0.5);
            $pdf->Line(30, $y, 180, $y);
            $y += 6;

            // ── Titre ─────────────────────────────────────────────
            $this->pdfSetFont($pdf, $fontSerif, 'B', 22);
            $pdf->SetTextColor(26, 26, 46);
            $pdf->SetXY(20, $y);
            $pdf->Cell(170, 10, mb_strtoupper($title), 0, 1, 'C');
            $y += 12;

            // ── Sous-titre ────────────────────────────────────────
            $this->pdfSetFont($pdf, $fontSerif, 'I', 11);
            $pdf->SetTextColor(100, 80, 40);
            $pdf->SetXY(20, $y);
            $pdf->Cell(170, 8, $subtitle, 0, 1, 'C');
            $y += 14;

            // ── Tableau des informations ──────────────────────────
            $fields = [
                $engine->get('certificate_email', 'certificate_pdf_label_product', $lang)       => $productName,
                $engine->get('certificate_email', 'certificate_pdf_label_serial', $lang)         => $serial,
                $engine->get('certificate_email', 'certificate_pdf_label_order_date', $lang)     => $dateStr,
                $engine->get('certificate_email', 'certificate_pdf_label_certified_date', $lang) => $issuedStr,
                $engine->get('certificate_email', 'certificate_pdf_label_owner', $lang)          => $customerName,
                $engine->get('certificate_email', 'certificate_pdf_label_order', $lang)          => '#' . (int) $order->id,
            ];

            foreach ($fields as $label => $value) {
                $this->pdfSetFont($pdf, $fontSans, 'B', 9);
                $pdf->SetTextColor(130, 100, 50);
                $pdf->SetXY(25, $y);
                $pdf->Cell(50, 7, mb_strtoupper($label), 0, 0, 'L');

                $this->pdfSetFont($pdf, $fontSans, '', 10);
                $pdf->SetTextColor(26, 26, 46);
                $pdf->SetXY(75, $y);
                $pdf->Cell(115, 7, $value, 0, 1, 'L');

                // Filet léger sous chaque ligne
                $pdf->SetDrawColor(220, 200, 170);
                $pdf->SetLineWidth(0.2);
                $pdf->Line(25, $y + 7, 185, $y + 7);
                $y += 9;
            }

            $y += 6;

            // ── Note de l'artisan ─────────────────────────────────
            if ($artisanNote !== '') {
                $this->pdfSetFont($pdf, $fontSerif, 'I', 10);
                $pdf->SetTextColor(80, 60, 30);
                $pdf->SetXY(25, $y);
                $pdf->MultiCell(160, 6, '"' . $artisanNote . '"', 0, 'C');
                $y = $pdf->GetY() + 6;
            }

            // ── Corps du texte ────────────────────────────────────
            $this->pdfSetFont($pdf, $fontSans, '', 9);
            $pdf->SetTextColor(100, 100, 100);
            $pdf->SetXY(25, $y);
            $pdf->MultiCell(160, 5, $bodyText, 0, 'C');
            $y = $pdf->GetY() + 10;

            // ── QR code (optionnel) ───────────────────────────────
            if ($qrEnabled) {
                // cert_qr_url n'est validée qu'avec Validate::isUrl() + préfixe
                // https:// (BO) — rien n'empêche un marchand d'y saisir une URL
                // contenant déjà une query string (ex. https://x.fr/verify?ref=y).
                // Concaténer '?cert=' dans ce cas produit une URL invalide
                // ('...?ref=y?cert=...') : le QR de TOUS les certificats émis
                // avec cette config pointe vers un lien cassé.
                $qrSeparator = strpos($qrBaseUrl, '?') !== false ? '&' : '?';
                $qrUrl = rtrim($qrBaseUrl, '/') . $qrSeparator . 'cert=' . urlencode($serial);
                $pdf->write2DBarcode($qrUrl, 'QRCODE,H', 25, $y, 28, 28);

                $this->pdfSetFont($pdf, $fontSans, '', 7);
                $pdf->SetTextColor(150, 150, 150);
                $pdf->SetXY(55, $y + 8);
                $pdf->Cell(130, 5, $engine->get('certificate_email', 'certificate_pdf_qr_hint', $lang), 0, 0, 'L');
                $pdf->SetXY(55, $y + 14);
                $pdf->Cell(130, 5, $qrUrl, 0, 0, 'L');
                $y += 32;
            }

            // ── Signature ─────────────────────────────────────────
            $pdf->SetDrawColor(179, 139, 89);
            $pdf->SetLineWidth(0.5);
            $pdf->Line(30, $y, 180, $y);
            $y += 4;

            if ($sigPath !== '') {
                $pdf->Image($sigPath, 80, $y, 50, 0);
                $y += 22;
            }

            $this->pdfSetFont($pdf, $fontSans, 'I', 9);
            $pdf->SetTextColor(100, 80, 40);
            $pdf->SetXY(20, $y);
            $pdf->Cell(170, 6, strtr($engine->get('certificate_email', 'certificate_pdf_signature', $lang), $pdfVars), 0, 1, 'C');

            // ── Pied de page ──────────────────────────────────────
            $this->pdfSetFont($pdf, $fontSans, '', 7);
            $pdf->SetTextColor(180, 160, 130);
            $pdf->SetXY(20, 270);
            $pdf->Cell(170, 5, strtr($engine->get('certificate_email', 'certificate_pdf_footer', $lang), $pdfVars), 0, 0, 'C');

            $pdfContent = $pdf->Output('certificate_' . $serial . '.pdf', 'S');

        } catch (\Throwable $e) {
            return ['error' => AdminTranslator::tVars('msg.certificate_pdf_error', ['error' => $e->getMessage()])];
        }

        // Sauvegarde optionnelle sur disque
        $dir  = _PS_MODULE_DIR_ . 'neria/certificates/';
        $file = 'cert_' . preg_replace('/[^a-z0-9_\-]/i', '_', $serial) . '.pdf';
        $path = '';
        if (!is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }
        if (is_dir($dir)) {
            // file_put_contents() peut échouer silencieusement (disque plein,
            // permissions, quota) — sans vérifier son retour, $path était
            // enregistré en DB même si le fichier n'existait pas ou était
            // tronqué, sans que rien ne le détecte ni ne le journalise.
            $written = @file_put_contents($dir . $file, $pdfContent);
            if ($written !== false && $written === strlen($pdfContent)) {
                $path = 'certificates/' . $file;
            } elseif (class_exists('WatchdogManager')) {
                (new \WatchdogManager($this->module))->warning(
                    'Échec d\'écriture du PDF certificat sur disque : ' . $dir . $file,
                    '', 'CertificateManager'
                );
            }
        }

        // Même assainissement que $file ci-dessus (whitelist alphanumérique)
        // — auparavant $serial brut était utilisé ici, sans assainissement,
        // alors qu'il est saisi librement par l'admin en BO (cert_serial).
        // Un guillemet dans le numéro de série pouvait rompre l'attribut
        // filename="..." de l'en-tête Content-Disposition au téléchargement
        // (neria.php, action cert_download).
        $safeSerial = preg_replace('/[^a-z0-9_\-]/i', '_', $serial);

        return ['content' => $pdfContent, 'path' => $path, 'filename' => 'certificat_' . $safeSerial . '.pdf'];
    }

