    /**
     * Envoie le certificat par email via le pipeline Neria standard
     * (Mail::Send → hook actionEmailSendBefore → EmailRenderer), comme tous
     * les autres templates du module — design, traduction 19 langues et
     * détection automatique de la langue du client comprises. Auparavant
     * cet envoi utilisait mail() natif avec un HTML entièrement codé en dur
     * en français : un client non-francophone recevait donc son certificat
     * (email de luxe, contenu officiel) intégralement en français, quelle
     * que soit sa langue configurée — jamais rendu via le template
     * certificate_email (ni {neria_trad}, ni auto-détection de langue).
     * Mail::Send() supporte nativement les pièces jointes (paramètre
     * $fileAttachment), donc le PDF reste attaché sans MIME manuel.
     */
    private function sendCertificateEmail(
        string $to,
        string $customerName,
        string $productName,
        string $serial,
        string $pdfContent,
        \Order $order,
        int    $idLang
    ): string {
        if (!\Validate::isEmail($to)) {
            return AdminTranslator::t('msg.certificate_recipient_invalid');
        }

        // id_shop DE LA COMMANDE, pas Context::getContext()->shop (contexte
        // BO de l'employé qui déclenche l'émission) — même correctif que
        // l'INSERT en base dans issue() ci-dessus : un employé en contexte
        // "toutes les boutiques" (ou dont le contexte BO courant diffère de
        // la boutique de la commande) émettant un certificat pour une
        // commande d'une AUTRE boutique envoyait sinon l'email avec la
        // config SMTP/expéditeur de la MAUVAISE boutique (Mail::Send() lit
        // $idShop pour résoudre la config d'envoi par boutique).
        $idShop   = (int) $order->id_shop;
        $filename = 'certificat_' . preg_replace('/[^a-z0-9_\-]/i', '_', $serial) . '.pdf';

        // getShopDomainSsl() est lié au CONTEXTE courant, pas à un id_shop
        // passé en paramètre (contrairement à Mail::Send() ci-dessous) —
        // bascule temporaire vers la vraie boutique de la commande, le temps
        // de résoudre {shop_url}, même pattern que BehavioralCronManager.
        // Sans ça, {shop_url} pointait vers le domaine du contexte BO de
        // l'employé au lieu de celui de la boutique réelle de la commande.
        $originalShop = \Context::getContext()->shop;
        if ((int) $originalShop->id !== $idShop) {
            \Context::getContext()->shop = new \Shop($idShop);
        }
        $shopUrl = \Tools::getShopDomainSsl(true, true);
        \Context::getContext()->shop = $originalShop;

        $vars = [
            '{firstname}'      => $customerName,
            '{customer_name}'  => $customerName,
            '{product_name}'   => $productName,
            '{serial_number}'  => $serial,
            '{id_order}'       => (int) $order->id,
            '{order_name}'     => $order->reference,
            // Configuration::get(..., $idShop) : round 106, même piège que
            // {shop_url} juste au-dessus (déjà scopé via la bascule
            // temporaire de Context::shop) — {shop_name}, lui, était résolu
            // via le contexte non scopé, restauré à $originalShop juste
            // avant cette ligne.
            '{shop_name}'      => (string) \Configuration::get('PS_SHOP_NAME', null, null, $idShop),
            '{shop_url}'       => $shopUrl,
        ];

        $sent = \Mail::Send(
            $idLang,
            'certificate_email',
            '', // sujet auto-traduit depuis greeting_main (EmailRenderer)
            $vars,
            $to,
            $customerName !== '' ? $customerName : null,
            null,
            null,
            ['content' => $pdfContent, 'name' => $filename, 'mime' => 'application/pdf'],
            null,
            _PS_MODULE_DIR_ . 'neria/mails/',
            false,
            $idShop
        );

        return $sent ? '' : AdminTranslator::t('msg.certificate_mail_send_failed');
    }

