                `id_certificate`  INT(11)      NOT NULL AUTO_INCREMENT,
                `id_shop`         INT(11)      NOT NULL DEFAULT 1,
                `id_customer`     INT UNSIGNED NOT NULL DEFAULT 0,
                `id_order`        INT(11)      NOT NULL,
                `id_product`      INT(11)      NOT NULL,
