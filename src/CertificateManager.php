    public function getAll(int $limit = 100, int $offset = 0): array
    {
        return $this->db->executeS(
            'SELECT c.*, o.reference AS order_ref
             FROM `' . _DB_PREFIX_ . self::TABLE . '` c
             LEFT JOIN `' . _DB_PREFIX_ . 'orders` o ON o.`id_order` = c.`id_order`
             WHERE c.`id_shop` = ' . $this->idShop . '
             ORDER BY c.`date_issued` DESC
             LIMIT ' . (int) $limit . ' OFFSET ' . (int) $offset
        ) ?: [];
    }

    public function countAll(): int
    {
        return (int) $this->db->getValue(
            'SELECT COUNT(*) FROM `' . _DB_PREFIX_ . self::TABLE . '`
             WHERE `id_shop` = ' . $this->idShop
        );
    }

    public function getByOrder(int $idOrder): array
    {
        // Pas de filtre `id_shop` = $this->idShop (contexte BO courant de
        // l'employé) : appelé depuis hookDisplayAdminOrderMainBottom, dont
        // le contexte de boutique en tête de BO peut différer de celle de
        // LA COMMANDE affichée (cas normal en multi-boutique). Avec ce
        // filtre, un certificat émis pour la commande — enregistré sous
        // `id_order` DE LA COMMANDE (round précédent, voir issue()) —
        // redevenait invisible sur la fiche commande elle-même dès que le
        // contexte BO différait, risquant une réémission en double.
        // id_order est déjà une clé globalement unique en multi-boutique
        // PrestaShop : filtrer dessus suffit à scoper la requête à la
        // bonne commande.
        return $this->db->executeS(
            'SELECT * FROM `' . _DB_PREFIX_ . self::TABLE . '`
             WHERE `id_order` = ' . $idOrder . '
             ORDER BY `date_issued` DESC'
        ) ?: [];
    }

    /**
     * KPIs pour l'onglet Certificats : total émis, taux d'envoi email,
     * tendance vs mois précédent, top 5 produits certifiés.
     */
    public function getStats(): array
    {
        $table = _DB_PREFIX_ . self::TABLE;

        $total   = (int) $this->db->getValue(
            "SELECT COUNT(*) FROM `{$table}` WHERE `id_shop` = {$this->idShop}"
        );
        $emailed = (int) $this->db->getValue(
            "SELECT COUNT(*) FROM `{$table}` WHERE `id_shop` = {$this->idShop} AND `emailed` = 1"
        );
        $thisMonth = (int) $this->db->getValue(
            "SELECT COUNT(*) FROM `{$table}`
             WHERE `id_shop` = {$this->idShop}
               AND `date_issued` >= DATE_FORMAT(NOW(), '%Y-%m-01')"
        );
        $lastMonth = (int) $this->db->getValue(
            "SELECT COUNT(*) FROM `{$table}`
             WHERE `id_shop` = {$this->idShop}
               AND `date_issued` >= DATE_FORMAT(DATE_SUB(NOW(), INTERVAL 1 MONTH), '%Y-%m-01')
               AND `date_issued` <  DATE_FORMAT(NOW(), '%Y-%m-01')"
        );
        // Round 120 : $lastMonthComparable, dédié à trend_pct — $thisMonth
        // ne couvre que le 1er du mois à AUJOURD'HUI (fenêtre partielle),
        // alors que $lastMonth (affiché tel quel dans 'last_month') couvre
        // le mois précédent ENTIER. Comparer $thisMonth à $lastMonth
        // directement (comme trend_pct le faisait) revient à comparer des
        // fenêtres de durées différentes — même famille de bug que rounds
        // 117/118. En tout début de mois, trend_pct affichait une chute
        // artificielle massive (ex. -74% le 8 août avec un rythme
        // d'émission pourtant stable), et une hausse trompeuse en toute fin
        // de mois. $lastMonthComparable borne le mois précédent au MÊME
        // nombre de jours écoulés que $thisMonth.
        $lastMonthComparable = (int) $this->db->getValue(
            "SELECT COUNT(*) FROM `{$table}`
             WHERE `id_shop` = {$this->idShop}
               AND `date_issued` >= DATE_FORMAT(DATE_SUB(NOW(), INTERVAL 1 MONTH), '%Y-%m-01')
               AND `date_issued` <  DATE_ADD(DATE_FORMAT(DATE_SUB(NOW(), INTERVAL 1 MONTH), '%Y-%m-01'), INTERVAL DAY(NOW()) DAY)"
        );
        $topProducts = $this->db->executeS(
            "SELECT `product_name`, COUNT(*) AS cnt
             FROM `{$table}`
             WHERE `id_shop` = {$this->idShop}
             GROUP BY `product_name`
             ORDER BY cnt DESC
             LIMIT 5"
        ) ?: [];

        return [
            'total'        => $total,
            'emailed'      => $emailed,
            'email_rate'   => $total > 0 ? round($emailed / $total * 100, 1) : 0.0,
            'this_month'   => $thisMonth,
            'last_month'   => $lastMonth,
            'trend_pct'    => $lastMonthComparable > 0
                ? round((($thisMonth - $lastMonthComparable) / $lastMonthComparable) * 100, 1)
                : ($thisMonth > 0 ? 100.0 : 0.0),
            'top_products' => $topProducts,
        ];
    }

    public function delete(int $idCertificate): void
    {
        $row = $this->db->getRow(
            'SELECT `pdf_path` FROM `' . _DB_PREFIX_ . self::TABLE . '`
             WHERE `id_certificate` = ' . $idCertificate . '
               AND `id_shop` = ' . $this->idShop
        );
        if (!$row) {
            return;
        }
        if ($row['pdf_path']) {
            $file = _PS_MODULE_DIR_ . 'neria/' . $row['pdf_path'];
            if (file_exists($file)) {
                @unlink($file);
            }
        }
        $this->db->delete(self::TABLE, '`id_certificate` = ' . $idCertificate . ' AND `id_shop` = ' . $this->idShop);
    }

