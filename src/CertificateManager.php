                `serial_number`   VARCHAR(100) NOT NULL,
                `customer_name`   VARCHAR(255) NOT NULL DEFAULT "",
                `product_name`    VARCHAR(255) NOT NULL DEFAULT "",
                `artisan_note`    TEXT         DEFAULT NULL,
